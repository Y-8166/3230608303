def main():
    for p in sorted(CASES.glob('*/案例/CASE-*/数据字典.md')):
        cid = '-'.join(p.parent.name.split('-')[:2])
        if cid not in DATA:
            continue
        text = p.read_text('utf-8')
        if '计数结构判定' in text:
            print('已有，跳过', cid)
            continue
        d = DATA[cid]
        # 找最后一个 ## 标题的编号
        heads = [ln for ln in text.split('\n') if ln.startswith('## ')]
        nums = []
        for h in heads:
            head = h[3:].split('.')[0].strip()
            if head.isdigit():
                nums.append(int(head))
        num = max(nums) if nums else len(heads)
        sec = SEC.format(num=num, rows=d['rows'], concl=d['concl'])
        if '## ' + str(num) + '. 变更历史' in text:
            old = '## ' + str(num) + '. 变更历史'
            text = text.replace(old, '## ' + str(num + 1) + '. 变更历史', 1)
            text = text.replace('## ' + str(num + 1) + '. 变更历史', sec + '\n## ' + str(num + 1) + '. 变更历史', 1)
        else:
            text = text.rstrip() + '\n\n' + sec
        p.write_text(text, 'utf-8')
        print('补入', cid, '第', num, '节')


if __name__ == '__main__':
    main()
